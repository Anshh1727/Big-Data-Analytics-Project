-- BA4301 HR Analytics schema (PostgreSQL 15+). The source is one CSV; the dimensions
-- and subject-area tables below are derived from that single flat file.
CREATE SCHEMA IF NOT EXISTS hr_analytics;
SET search_path TO hr_analytics, public;

CREATE TABLE IF NOT EXISTS raw_hr_employees (
  employee_id text, department text, gender text, age text, job_title text,
  hire_date text, years_at_company text, education_level text,
  performance_score text, monthly_salary text, work_hours_per_week text,
  projects_handled text, overtime_hours text, sick_days text,
  remote_work_frequency text, team_size text, training_hours text,
  promotions text, employee_satisfaction_score text, resigned text
);

CREATE TABLE IF NOT EXISTS departments (
  department_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_name text NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS job_roles (
  job_role_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_title text NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS employees (
  employee_id bigint PRIMARY KEY,
  department_id integer NOT NULL REFERENCES departments(department_id),
  job_role_id integer NOT NULL REFERENCES job_roles(job_role_id),
  gender text,
  age integer CHECK (age BETWEEN 16 AND 100),
  hire_date timestamp,
  years_at_company numeric(6,2) CHECK (years_at_company >= 0),
  education_level text,
  resigned boolean NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_employees_department ON employees(department_id);
CREATE INDEX IF NOT EXISTS idx_employees_role ON employees(job_role_id);
CREATE INDEX IF NOT EXISTS idx_employees_resigned ON employees(resigned);

CREATE TABLE IF NOT EXISTS employee_workforce_metrics (
  employee_id bigint PRIMARY KEY REFERENCES employees(employee_id) ON DELETE CASCADE,
  work_hours_per_week numeric(7,2) CHECK (work_hours_per_week >= 0),
  projects_handled integer CHECK (projects_handled >= 0),
  overtime_hours numeric(7,2) CHECK (overtime_hours >= 0),
  sick_days integer CHECK (sick_days >= 0),
  remote_work_frequency numeric(6,2) CHECK (remote_work_frequency BETWEEN 0 AND 100),
  team_size integer CHECK (team_size >= 1),
  training_hours numeric(7,2) CHECK (training_hours >= 0),
  promotions integer CHECK (promotions >= 0),
  employee_satisfaction_score numeric(5,2) CHECK (employee_satisfaction_score BETWEEN 0 AND 5)
);
CREATE TABLE IF NOT EXISTS employee_performance (
  employee_id bigint PRIMARY KEY REFERENCES employees(employee_id) ON DELETE CASCADE,
  performance_score numeric(5,2) CHECK (performance_score BETWEEN 0 AND 5)
);
CREATE TABLE IF NOT EXISTS employee_compensation (
  employee_id bigint PRIMARY KEY REFERENCES employees(employee_id) ON DELETE CASCADE,
  monthly_salary numeric(14,2) CHECK (monthly_salary >= 0)
);
